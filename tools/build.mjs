// Build step: reads timeline/timing.json and
//  1) writes index.html (scene slots + audio stems) with exact timings
//  2) injects each scene's local cue table between /*CUES*/ ... /*ENDCUES*/ markers
// usage: node tools/build.mjs
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const T = JSON.parse(fs.readFileSync(path.join(ROOT, "timeline/timing.json"), "utf8"));
const TOTAL = Math.ceil(T.duration * 30) / 30;
const f3 = (x) => +x.toFixed(3);

// --only sXX : write preview-sXX.html containing just that scene (starting at 0) for fast iteration
const oi = process.argv.indexOf("--only");
const ONLY = oi > 0 ? process.argv[oi + 1] : null;
let slots = "";
for (const sec of T.sections) {
  const file = path.join(ROOT, "compositions", `${sec.id}.html`);
  const dur = f3(sec.end - sec.start);
  if (fs.existsSync(file)) {
    const cues = {};
    for (const [id, l] of Object.entries(T.lines))
      if (l.section === sec.id) cues[id] = [f3(l.start - sec.start), f3(l.end - sec.start), l.text];
    let src = fs.readFileSync(file, "utf8");
    const block = `/*CUES*/ const CUES = ${JSON.stringify(cues)}; const DUR = ${dur}; /*ENDCUES*/`;
    src = src.replace(/\/\*CUES\*\/[\s\S]*?\/\*ENDCUES\*\//, block);
    fs.writeFileSync(file, src);
  } else console.warn("missing scene file", sec.id);
  if (!fs.existsSync(file) || (ONLY && sec.id !== ONLY)) continue;
  slots += `
      <!-- ${sec.name} -->
      <div id="el-${sec.id}" data-composition-id="${sec.id}" data-composition-src="compositions/${sec.id}.html"
        data-start="${ONLY ? 0 : f3(sec.start)}" data-duration="${dur}" data-track-index="1" data-width="1920" data-height="1080"></div>`;
}

const total = ONLY ? f3(T.sections.find((s) => s.id === ONLY).end - T.sections.find((s) => s.id === ONLY).start) : TOTAL;
const aStart = ONLY ? -T.sections.find((s) => s.id === ONLY).start : 0;
const html = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1920, height=1080" />
    <title>Why Can't You Tickle Yourself? — Randos in 60s</title>
    <!-- GENERATED by tools/build.mjs from timeline/timing.json — edit scenes in compositions/, not here -->
    <script src="assets/lib/gsap.min.js"></script>
    <script src="assets/lib/rig.js"></script>
    <style>
      @font-face { font-family: "HandSC"; src: url("assets/fonts/PatrickHandSC.woff2") format("woff2"); }
      @font-face { font-family: "Hand"; src: url("assets/fonts/PatrickHand.woff2") format("woff2"); }
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { margin: 0; overflow: hidden; background: #FBF8F1; }
      #root { position: relative; width: 100%; height: 100%; overflow: hidden; background: #FBF8F1; }
      [data-composition-id="root"] > div[data-composition-src] { position: absolute; inset: 0; }
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="root" data-start="0" data-duration="${total}" data-width="1920" data-height="1080">${slots}

      <!-- audio stems (built by tools/tts.py and tools/audio.py) -->
      <audio id="vo" src="assets/audio/narration.m4a" data-start="0" data-media-start="${-aStart}" data-duration="${total}" data-track-index="10" data-volume="1"></audio>
      <audio id="music" src="assets/audio/music.m4a" data-start="0" data-media-start="${-aStart}" data-duration="${total}" data-track-index="11" data-volume="1"></audio>
      <audio id="sfx" src="assets/audio/sfx.m4a" data-start="0" data-media-start="${-aStart}" data-duration="${total}" data-track-index="12" data-volume="1"></audio>
    </div>
    <script>
      window.__timelines["root"] = gsap.timeline({ paused: true });
    </script>
  </body>
</html>
`;
const out = ONLY ? `preview-${ONLY}.html` : "index.html";
fs.writeFileSync(path.join(ROOT, out), html);
console.log(out, "written; total", total, "s;", T.sections.length, "scenes");
